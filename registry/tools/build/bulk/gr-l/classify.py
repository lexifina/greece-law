def norm(s: str) -> str:
    s = unicodedata.normalize('NFD', (s or '').lower())
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn')
    s = s.replace('ς', 'σ').replace('`', "'").replace('’', "'").replace('΄', "'")
    # Latin look-alikes typed into Greek words
    s = re.sub(r'(?<=[α-ω])[aeiokxtp](?=[α-ω])|(?<=[α-ω])[aeiokxtp]\b|\b[aeiokxtp](?=[α-ω])',
               lambda m: dict(zip('aeiokxtp', 'αειοκχτρ'))[m.group(0)], s)
    return re.sub(r'\s+', ' ', s).strip()


