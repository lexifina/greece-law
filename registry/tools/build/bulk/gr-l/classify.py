def classify(subject: str) -> tuple[str | None, str]:
    s = norm(subject)
    if not s:
        return None, 'empty subject'
    if REJECTED.search(s):
        return None, 'rejected (μη έγκριση)'
    if PREPARATORY.search(CITED_PROPOSAL.sub(' ', s)):
        return None, 'preparatory (εισήγηση/παραπομπή/γνώμη/σχέδιο)'
    if COMMITTEE_FIRST.search(s):
        return None, 'committee decision (forwarded to the council)'
    if NEVER.search(s):
        return None, 'administrative (payment, procurement, staff, contract, case ...)'
    if OEY.search(s):
        return (None, 'staff measure under the ΟΕΥ') if OEY_NOT.search(s) else ('oey', 'ΟΕΥ')
    if KANONISMOS.search(s) and not EU.search(s) and not KANONISMOS_NOT.search(s):
        return 'kanonismos', 'κανονισμός'
    if OWN_REG.search(s) and not re.search(r'παραβασ|προστιμ|κανονισμ\w* \(?(εε|εοκ|ε\.ε\.)', s):
        return 'kanonismos', 'κανονισμός λειτουργίας (δομή με χρηματοδότηση)'
    if KANONISTIKI.search(s) and not KANONISTIKI_NOT.search(s) and not EU.search(s):
        return 'kanonistiki', 'κανονιστική απόφαση'
    if TELI.search(s) and not TELI_NOT.search(s) and not INDIVIDUAL.search(s):
        return 'teli', 'τέλη/συντελεστές'
    if KYKLO.search(s) and not KYKLO_NOT.search(s) and not INDIVIDUAL.search(s):
        return 'kykloforia', 'ρυθμίσεις κυκλοφορίας/στάθμευσης'
    return None, 'no regulatory subject'


def rows(paths):
    for p in paths:
        op = gzip.open if p.endswith('.gz') else open
        with op(p, 'rt', encoding='utf-8') as f:
            for line in f:
                if line.strip():
                    yield json.loads(line)


def main(argv: list[str]) -> None:
    import collections
    import random
    show = int(argv[argv.index('--show') + 1]) if '--show' in argv else 0
    paths = [a for a in argv if not a.startswith('--') and not a.isdigit()]
    seen, by = set(), collections.defaultdict(list)
    for r in rows(paths):
        if r['ada'] in seen:
            continue
        seen.add(r['ada'])
        c, why = classify(r['subject'])
        by[c or 'none:' + why].append(r)
    for k in sorted(by, key=lambda k: -len(by[k])):
        print(f'{len(by[k]):7d} {k}')
    rnd = random.Random(7)
    for k in sorted(by):
        if show and not k.startswith('none'):
            print(f'== {k}')
            for r in rnd.sample(by[k], min(show, len(by[k]))):
                print('   ', r['subject'].replace('\n', ' ')[:160])


if __name__ == '__main__':
    main(sys.argv[1:])
